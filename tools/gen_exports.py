def is_guard(name: str) -> bool:
    return re.fullmatch(r'(VPX_VPX_\w+_H_|MKV\w+_H_|LIBWEBM_COMMON_\w+_H_|COMMON_WEBMIDS_H_)', name) is not None


def is_feature_test(name: str) -> bool:
    """VPX_CTRL_<id>: empty, defined beside each typed control so code can test for it with #ifdef."""
    return name.startswith('VPX_CTRL_') and name not in STAY


def constants(c) -> list[str]:
    names = [m for m in c.macros if not is_guard(m) and m not in STAY and m not in FUNCTIONS and m not in CONSTEXPR and not is_feature_test(m)]
    unknown = [m for m in names if m in c.function_like]
    if unknown:
        sys.exit('function-like macros with no mapping: ' + ', '.join(unknown))
    return names


HEAD = """// Generated by tools/gen_exports.py from libvpx 1.17.0's and libwebm 1.0.0.32's
// headers — do not edit by hand.
//
"""


def libvpx_module(c, functions, data) -> str:
    out = [HEAD + """// mcpplibs.mwrap.libvpx — libvpx 1.17.0, the VP9 video codec, as a C++ module:
// every type, enumerator and function of the headers upstream installs
// (vpx_codec.h, vpx_image.h, vpx_frame_buffer.h, vpx_encoder.h with
// vpx_ext_ratectrl.h and vpx_tpl.h, vpx_decoder.h, vp8.h, vp8cx.h, vp8dx.h),
// the upstream globals unchanged: the encoder and decoder API, images and
// frame buffers, the control ids, the VP9 codec interfaces. The headers'
// typed controls (static functions made by VPX_CTRL_USE_TYPE) are adapted
// under the same names in namespace mcpplibs::mwrap::libvpx. It re-exports
// the WebM container (mcpplibs.mwrap.libvpx.webm: libwebm's mkvmuxer and
// mkvparser) and the macro mappings (mcpplibs.mwrap.libvpx.macros). The
// libraries are compat.libvpx and compat.libwebm, built from the same tags.
module;
#include <mwrap/libvpx/macros.hpp>

export module mcpplibs.mwrap.libvpx;

export import mcpplibs.mwrap.libvpx.webm;
export import mcpplibs.mwrap.libvpx.macros;
"""]
    out.append(f'// types ({len(c.types)}: typedef names and struct and enum tags)')
    out += [f'export using ::{t};' for t in c.types]
    out.append(f'\n// enumerators ({len(c.enumerators)})')
    out += [f'export using ::{e};' for e in c.enumerators]
    out.append(f'\n// functions ({len(functions)}: what upstream exports; VP8\'s interfaces are not built)')
    out += [f'export using ::{f};' for f in functions]
    out.append(f'\n// the codec interfaces ({len(data)})')
    out += [f'export using ::{d};' for d in data]
    out.append(f"""
// The typed controls ({len(c.controls)}): `vpx_codec_control(ctx, ID, data)` in C
// is vpx_codec_control_ID(ctx, ID, data), a static function of the headers;
// here an exported one of the same name and signature.
export namespace mcpplibs::mwrap::libvpx {{
""")
    for k in c.controls:
        dep = '[[deprecated]] ' if k.deprecated else ''
        params = 'vpx_codec_ctx_t* ctx, int ctrl_id' + (f', {k.type} data' if k.type else '')
        out.append(f'{dep}vpx_codec_err_t vpx_codec_control_{k.id}({params});')
    out.append('\n}  // namespace mcpplibs::mwrap::libvpx\n')
    return '\n'.join(out)


def control_unit(c) -> str:
    out = [HEAD + """// The typed controls' bodies: upstream's own (VPX_CTRL_USE_TYPE's), a call of
// the variadic vpx_codec_control_ with the typed argument.
module;
#include <mwrap/libvpx/macros.hpp>

module mcpplibs.mwrap.libvpx;

namespace mcpplibs::mwrap::libvpx {
"""]
    for k in c.controls:
        params = 'vpx_codec_ctx_t* ctx, int ctrl_id' + (f', {k.type} data' if k.type else '')
        call = 'ctx, ctrl_id' + (', data' if k.type else '')
        out.append(f'vpx_codec_err_t vpx_codec_control_{k.id}({params}) {{ return ::vpx_codec_control_({call}); }}')
    out.append('\n}  // namespace mcpplibs::mwrap::libvpx\n')
    return '\n'.join(out)


def webm_module(w) -> str:
    includes = '\n'.join(f'#include <{h}>' for h in LIBWEBM_HEADERS)
    out = [HEAD + f"""// mcpplibs.mwrap.libvpx.webm — libwebm 1.0.0.32, the WebM (Matroska) container,
// as a C++ module: the classes, types, enumerators and functions of the
// headers of upstream's `webm` library in their own namespaces — mkvmuxer
// (Segment, the tracks, Frame, Colour, IMkvWriter and MkvWriter …), mkvparser
// (Segment, Tracks, Cluster, Block, IMkvReader and MkvReader …) and libwebm
// (the element ids, the colour copiers). The namespace-scope constants of the
// headers have internal linkage, so they are not exported by name: their
// values are under the same names in mcpplibs::mwrap::libvpx::mkvmuxer and
// mcpplibs::mwrap::libvpx::mkvparser. The library is compat.libwebm.
module;
{includes}

export module mcpplibs.mwrap.libvpx.webm;
"""]
    for name, ns in w.namespaces.items():
        out.append(f'export namespace {name} {{')
        out.append(f'// types ({len(ns.classes)})')
        out += [f'using ::{name}::{t};' for t in ns.classes]
        if ns.enumerators:
            out.append(f'// enumerators ({len(ns.enumerators)})')
            out += [f'using ::{name}::{e};' for e in ns.enumerators]
        out.append(f'// functions ({len(ns.functions)})')
        out += [f'using ::{name}::{f};' for f in ns.functions]
        out.append(f'}}  // namespace {name}\n')
    for name, ns in w.namespaces.items():
        if not ns.constants:
            continue
        out.append(f'export namespace mcpplibs::mwrap::libvpx::{name} {{')
        for k, t in ns.constants.items():
            out.append(f'inline constexpr auto {k} = ::{name}::{k};  // {t}')
        out.append(f'}}  // namespace mcpplibs::mwrap::libvpx::{name}\n')
    return '\n'.join(out)


def capture_header(c) -> str:
    names = constants(c)
    capture = '\n'.join(f'inline constexpr auto value_{m} = {m};' for m in names)
    calls = '\n'.join(f'inline {ret} ({name})({params}) {{ return {name}({args}); }}' for name, (ret, params, args, _) in FUNCTIONS.items())
    computes = '\n'.join(f'constexpr {ret} ({name})({params}) {{ return {name}({args}); }}' for name, (ret, params, args, _) in CONSTEXPR.items())
    undef = '\n'.join(f'#undef {m}' for m in names + list(FUNCTIONS) + list(CONSTEXPR))
    return HEAD + f"""// The values of libvpx's macros, captured before src/macros.cppm undefines
// them (the global module fragment holds only what the preprocessor includes).
#pragma once
#include <mwrap/libvpx/macros.hpp>

namespace mwrap_libvpx_capture {{
{capture}
}}  // namespace mwrap_libvpx_capture

namespace mwrap_libvpx_function {{
{calls}
{computes}
}}  // namespace mwrap_libvpx_function

{undef}
"""


def macros_module(c) -> str:
    names = constants(c)
    funcs = []
    for name, (ret, params, args, doc) in FUNCTIONS.items():
        if doc:
            funcs.append(f'// {doc}')
        funcs.append(f'{ret} {name}({params});')
    return HEAD + f"""// mcpplibs.mwrap.libvpx.macros — the macros of libvpx's public headers (a named
// module cannot export a macro), under their original names in
// mcpplibs::mwrap::libvpx::macros:
//
//   - the {len(names)} constants (the ABI versions, VPX_CODEC_CAP_*, VPX_CODEC_USE_*,
//     VPX_FRAME_IS_*, VPX_EFLAG_*, VP8_EFLAG_*, VPX_DL_*, the layer limits,
//     the image format and plane constants …) as `inline constexpr`, of the
//     type the macro's expression has;
//   - vpx_codec_enc_init, vpx_codec_enc_init_multi, vpx_codec_dec_init and
//     vpx_codec_version_major/_minor/_patch as functions;
//   - VPX_VERSION_MAJOR/_MINOR/_PATCH(v) as constexpr functions.
//
// What stays a macro (in <mwrap/libvpx/macros.hpp>): vpx_codec_control (token
// concatenation; the typed controls are functions of the main module),
// VPX_CTRL_USE_TYPE*, VPX_CTRL_VOID, the empty VPX_CTRL_<id> feature tests
// for #ifdef, the declaration annotations and the include guards;
// tools/check_exports.py accounts for every macro.
module;
#include "macros_capture.hpp"

export module mcpplibs.mwrap.libvpx.macros;

export namespace mcpplibs::mwrap::libvpx::macros {{

{chr(10).join(f'inline constexpr auto {m} = mwrap_libvpx_capture::value_{m};' for m in names)}

{chr(10).join(funcs)}

{chr(10).join(('// ' + doc + chr(10) if doc else '') + f'constexpr {ret} {name}({params}) {{ return mwrap_libvpx_function::{name}({args}); }}' for name, (ret, params, args, doc) in CONSTEXPR.items())}

}}  // namespace mcpplibs::mwrap::libvpx::macros

namespace mcpplibs::mwrap::libvpx::macros {{
{chr(10).join(f'{ret} {name}({params}) {{ return mwrap_libvpx_function::{name}({args}); }}' for name, (ret, params, args, _) in FUNCTIONS.items())}
}}  // namespace mcpplibs::mwrap::libvpx::macros
"""


def link_test(c, functions, data) -> str:
    out = [HEAD + """// The address of every exported function and adapted control, and every codec
// interface, through the module only (no header): each is defined by
// compat.libvpx or by the module, so a program that calls any of them links.
import std;
import mcpplibs.mwrap.libvpx;

using fn = void (*)();

int main() {
    const fn functions[] = {"""]
    out += [f'        reinterpret_cast<fn>(&::{f}),' for f in functions]
    out += [f'        reinterpret_cast<fn>(&mcpplibs::mwrap::libvpx::vpx_codec_control_{k.id}),' for k in c.controls if not k.deprecated]
    out.append('    };')
    out.append('    const void* interfaces[] = {' + ', '.join(f'&::{d}' for d in data) + '};')
    out.append(f"""    int missing = 0;
    for (fn f : functions) missing += f == nullptr;
    for (const void* d : interfaces) missing += d == nullptr;
    std::println("{{}} functions and controls, {{}} codec interfaces: {{}}", std::size(functions), std::size(interfaces), missing ? "MISSING" : "all linked");
    return missing;
}}
""")
    return '\n'.join(out)


def macros_mix_test(c) -> str:
    out = [HEAD + """// Every mapping against the raw headers, in one translation unit that includes
// <mwrap/libvpx/macros.hpp> beside the import: each constant has its macro's
// type and value (the macro is set aside with push_macro around the
// comparison: while it is defined it expands even inside `m::NAME`); each
// function-like mapping answers what its macro does (a function-like macro is
// not expanded when its name is followed by `)`, so `(m::NAME)(args)` calls
// the function beside the macro `NAME(args)`); the header's
// vpx_codec_control macro and the adapted typed control set the same thing.
#include <mwrap/libvpx/macros.hpp>

import std;
import mcpplibs.mwrap.libvpx;

namespace m = mcpplibs::mwrap::libvpx::macros;
"""]
    for name in constants(c):
        out.append(f'constexpr auto raw_{name} = {name};')
        out.append(f'#pragma push_macro("{name}")\n#undef {name}')
        out.append(f'static_assert(std::is_same_v<decltype(raw_{name}), decltype(m::{name})> && raw_{name} == m::{name});')
        out.append(f'#pragma pop_macro("{name}")')
    out.append("""
static_assert((m::VPX_VERSION_MAJOR)(0x011100) == VPX_VERSION_MAJOR(0x011100) && (m::VPX_VERSION_MINOR)(0x011100) == VPX_VERSION_MINOR(0x011100) &&
              (m::VPX_VERSION_PATCH)(0x011102) == VPX_VERSION_PATCH(0x011102));

int main() {
    int failures = 0;
    auto check = [&](bool ok, const char* what) {
        std::println("{:<64} {}", what, ok ? "ok" : "FAILED");
        failures += !ok;
    };
    check((m::vpx_codec_version_major)() == vpx_codec_version_major() && (m::vpx_codec_version_minor)() == vpx_codec_version_minor() &&
              (m::vpx_codec_version_patch)() == vpx_codec_version_patch(),
          "vpx_codec_version_major/_minor/_patch");
    vpx_codec_enc_cfg_t cfg;
    check(vpx_codec_enc_config_default(vpx_codec_vp9_cx(), &cfg, 0) == VPX_CODEC_OK, "a default configuration");
    cfg.g_w = 64;
    cfg.g_h = 64;
    vpx_codec_ctx_t a, b;
    check((m::vpx_codec_enc_init)(&a, vpx_codec_vp9_cx(), &cfg, 0) == VPX_CODEC_OK && vpx_codec_enc_init(&b, vpx_codec_vp9_cx(), &cfg, 0) == VPX_CODEC_OK,
          "the mapped vpx_codec_enc_init beside the macro");
    // The header's typed control through its macro, and the module's adapted one.
    check(vpx_codec_control(&a, VP8E_SET_CPUUSED, 7) == VPX_CODEC_OK &&
              mcpplibs::mwrap::libvpx::vpx_codec_control_VP8E_SET_CPUUSED(&b, VP8E_SET_CPUUSED, 7) == VPX_CODEC_OK,
          "vpx_codec_control (the macro) and the adapted control");
#ifndef VPX_CTRL_VP9E_SET_ROW_MT
    check(false, "the VPX_CTRL_<id> feature tests are defined");
#endif
    vpx_codec_destroy(&a);
    vpx_codec_destroy(&b);
    vpx_codec_dec_cfg_t dcfg{};
    vpx_codec_ctx_t d;
    check((m::vpx_codec_dec_init)(&d, vpx_codec_vp9_dx(), &dcfg, 0) == VPX_CODEC_OK, "the mapped vpx_codec_dec_init");
    vpx_codec_destroy(&d);
    std::println("{}", failures ? "FAILED" : "all passed");
    return failures;
}
""")
    return '\n'.join(out)


