def render(root: Path) -> dict[str, str]:
    tops = fetch(root)
    c = c_surface(tops['libvpx'])
    text, data = exported_symbols(tops['libvpx'])
    missing = (set(text) - set(c.functions)) | (set(data) - set(c.data))
    if missing:
        sys.exit('exported by upstream, not declared by the headers: ' + ', '.join(sorted(missing)))
    w = cpp_surface(tops['libwebm'])
    return {
        'src/libvpx.cppm': libvpx_module(c, text, data),
        'src/control.cpp': control_unit(c),
        'src/webm.cppm': webm_module(w),
        'src/macros.cppm': macros_module(c),
        'src/macros_capture.hpp': capture_header(c),
        'tests/link_test.cpp': link_test(c, text, data),
        'tests/macros_mix_test.cpp': macros_mix_test(c),
    }


def main():
    root = Path(__file__).resolve().parents[1]
    files = render(root)
    stale = []
    for name, text in files.items():
        path = root / name
        if '--check' in sys.argv:
            if not path.exists() or path.read_text(encoding='utf-8') != text:
                stale.append(name)
        else:
            path.write_text(text, encoding='utf-8', newline='\n')
            print('wrote', name)
    if stale:
        sys.exit('stale (python3 tools/gen_exports.py): ' + ', '.join(stale))


if __name__ == '__main__':
    main()
